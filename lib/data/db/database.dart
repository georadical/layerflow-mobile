import 'package:drift/drift.dart';
import 'package:drift_flutter/drift_flutter.dart';

import '../../core/config/app_config.dart';

part 'database.g.dart';

/// Routes open on the device. Stores the minimum context needed to resume.
class Routes extends Table {
  /// Route UUID. The route is in state `verificada` (the domain is
  /// `borrador | verificada`; there is no "congelada").
  TextColumn get routeId => text()();

  /// Route census code (comes from the backend frame).
  TextColumn get codigo => text().nullable()();

  /// Last time the frame (GET) was fetched to resume.
  DateTimeColumn get lastFrameSyncAt => dateTime().nullable()();

  /// Last manual send attempt for this route (Spec 4, BR7): when it happened
  /// and how it ended (an AppConfig.push* code the UI translates). Null until
  /// the first attempt. Recorded on failures too — that is the whole point:
  /// a worker who missed the message can still tell the queue was tried.
  DateTimeColumn get lastPushAt => dateTime().nullable()();
  TextColumn get lastPushOutcome => text().nullable()();

  @override
  Set<Column<Object>> get primaryKey => {routeId};
}

/// One capture = one household. Local offline-first queue.
///
/// Invariants (enforced by the repository, not by the UI):
/// - `clientId` is the idempotency key (UUID generated by the app).
/// - `posicion` is monotonic, append-only per route (1, 2, 3…). It is NEVER
///   reordered or reassigned in the MVP.
/// - No coordinates: there is no lat/lon column anywhere.
/// - `loc` and `remoteId` are assigned by the server (loc = posicion × 5); they
///   are stored on sync.
class Captures extends Table {
  /// UUID generated by the app. Idempotency key with the backend.
  TextColumn get clientId => text()();

  TextColumn get routeId => text()();

  /// Walk counter (append-only).
  /// SQL column stays 'orden': the Dart name follows the contract rename
  /// (posicion, backend edf0f4f) without forcing a schema migration for a
  /// label users never see.
  IntColumn get posicion => integer().named('orden')();

  /// placa (address on the door). Optional: it may be left blank.
  TextColumn get placa => text().nullable()();

  /// manzana_catastral (from the route design). Optional.
  TextColumn get manzanaCatastral => text().nullable()();

  /// tipo_acceso (optional): e.g. puerta_calle / area_comun / otro.
  TextColumn get tipoAcceso => text().nullable()();

  /// Free-form observacion (optional).
  TextColumn get observacion => text().nullable()();

  /// loc assigned by the server (posicion × 5). Null until synced.
  IntColumn get loc => integer().nullable()();

  /// Pending relocation: the loc of the unit this one goes after (0 = start
  /// of route). Null = no mark. The contract is full-replacement, so this
  /// must ride on every push of the row or the backend clears it (Spec 2.1).
  IntColumn get insAfter => integer().nullable()();

  /// id of the remote census_code. Null until synced.
  TextColumn get remoteId => text().nullable()();

  /// pending | synced | error
  TextColumn get syncStatus =>
      text().withDefault(const Constant(AppConfig.syncPending))();

  /// Last sync error (diagnostics). Null if there is none.
  TextColumn get syncError => text().nullable()();

  DateTimeColumn get createdAt => dateTime()();
  DateTimeColumn get updatedAt => dateTime()();

  @override
  Set<Column<Object>> get primaryKey => {clientId};
}

@DriftDatabase(tables: [Routes, Captures])
class AppDatabase extends _$AppDatabase {
  AppDatabase([QueryExecutor? executor])
      : super(executor ?? driftDatabase(name: AppConfig.dbName));

  @override
  int get schemaVersion => 3;

  /// All added columns are nullable, so old rows come out as null — "no
  /// relocation mark" (v2) and "never attempted a send" (v3); no backfill.
  @override
  MigrationStrategy get migration => MigrationStrategy(
        onUpgrade: (m, from, to) async {
          if (from < 2) {
            await m.addColumn(captures, captures.insAfter);
          }
          if (from < 3) {
            await m.addColumn(routes, routes.lastPushAt);
            await m.addColumn(routes, routes.lastPushOutcome);
          }
        },
      );

  // ---- Routes ----

  Future<void> upsertRoute(RoutesCompanion route) =>
      into(routes).insertOnConflictUpdate(route);

  Future<Route?> getRoute(String routeId) =>
      (select(routes)..where((r) => r.routeId.equals(routeId)))
          .getSingleOrNull();

  Stream<Route?> watchRoute(String routeId) =>
      (select(routes)..where((r) => r.routeId.equals(routeId)))
          .watchSingleOrNull();

  Future<List<Route>> allRoutes() =>
      (select(routes)..orderBy([(r) => OrderingTerm.desc(r.lastFrameSyncAt)]))
          .get();

  // ---- Captures ----

  /// Next append-only `posicion` for the route: max(posicion)+1, or 1 if empty.
  Future<int> nextPosicion(String routeId) async {
    final maxExpr = captures.posicion.max();
    final query = selectOnly(captures)
      ..where(captures.routeId.equals(routeId))
      ..addColumns([maxExpr]);
    final row = await query.getSingle();
    final currentMax = row.read(maxExpr);
    return (currentMax ?? 0) + 1;
  }

  Stream<List<Capture>> watchCaptures(String routeId) {
    return (select(captures)
          ..where((c) => c.routeId.equals(routeId))
          ..orderBy([(c) => OrderingTerm.asc(c.posicion)]))
        .watch();
  }

  Future<List<Capture>> capturesForRoute(String routeId) {
    return (select(captures)
          ..where((c) => c.routeId.equals(routeId))
          ..orderBy([(c) => OrderingTerm.asc(c.posicion)]))
        .get();
  }

  Future<Capture?> getCapture(String clientId) =>
      (select(captures)..where((c) => c.clientId.equals(clientId)))
          .getSingleOrNull();

  Future<List<Capture>> pendingCaptures(String routeId) {
    return (select(captures)
          ..where((c) =>
              c.routeId.equals(routeId) &
              c.syncStatus.equals(AppConfig.syncSynced).not())
          ..orderBy([(c) => OrderingTerm.asc(c.posicion)]))
        .get();
  }

  Future<void> insertCapture(CapturesCompanion capture) =>
      into(captures).insert(capture);

  Future<void> upsertCapture(CapturesCompanion capture) =>
      into(captures).insertOnConflictUpdate(capture);

  Future<bool> updateCaptureRow(String clientId, CapturesCompanion patch) {
    return (update(captures)..where((c) => c.clientId.equals(clientId)))
        .write(patch)
        .then((rows) => rows > 0);
  }
}
